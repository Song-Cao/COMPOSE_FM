"""Finance case study, rebuilt with PURGED CHRONOLOGICAL splits and a fully held-out day.

FRAMING -- OBSERVATIONAL, NOT CAUSAL. Read this before any number below.
------------------------------------------------------------------------
This is ORDER-FLOW CONDITIONING, not intervention estimation. Nobody assigned the order
flow; it was generated by the same market whose state we then observe, so the "exposure"
tau is an OBSERVED covariate and not a dose anybody set. Three specific consequences,
which the previous version of this study did not state:

  * The estimand is a CONDITIONAL DISTRIBUTION, p(z_{i+1} | z_i, flow in window i), not a
    counterfactual "what would this window have done under different flow". Common causes
    (news, a large parent order being sliced, a funding-rate reset) drive both the flow and
    the subsequent return, so the fitted map is a predictive one.
  * The composition claim is correspondingly weaker here than in the organoid study: it is
    "does composing per-channel generators predict joint flow better than adding
    displacements", not "does the joint intervention do what composition says it would".
  * Nothing here licenses an execution or trading conclusion. The square-root impact law is
    cited as a stylised fact the fitted exposure response can be COMPARED against, not as
    a causal effect being recovered.

The biological case study carries the causal-composition claim (drug combinations really
were assigned). This one tests whether the same operator transfers to a domain with a
genuinely different exposure geometry.

WHY THE PREVIOUS SPLIT WAS INVALID
----------------------------------
`data_finance.impact_state` pairs consecutive bins: for sample i, z0 is the state of bin i
and z1 is the state of bin i+1. So samples i and i+1 SHARE bin i+1 -- one is a
read of the other's response. The previous split partitioned on exposure and composition
with no temporal constraint at all, so a training sample and a test sample routinely
shared a bin, and beyond that shared a volatility regime (realised vol is strongly
autocorrelated at the 10 s scale). Every held-out number was therefore contaminated.

WHAT THIS SCRIPT DOES INSTEAD
-----------------------------
  1. FULLY HELD-OUT DAY. 2025-06-05 is removed before anything is fitted -- not a random
     subset of it, the whole day. It is the only split here with no shared regime at all.
  2. PURGED CHRONOLOGICAL SPLIT on the remaining days. Days are cut into contiguous
     BLOCKS; blocks are assigned to train/test in chronological order; and at every
     train/test boundary an EMBARGO of `EMBARGO_WINDOWS` samples is dropped from the
     TRAINING SIDE ONLY. The test set is deliberately left intact -- trimming it would
     change the distribution the model is scored on, and one-sided purging already
     achieves the goal, since removing the training neighbours of a test window severs the
     overlap symmetrically (the audit verifies this directly by re-deriving the minimum
     train-test gap). One dropped sample would remove the shared-bin overlap; the embargo
     is set wider (default 30 windows = 5 minutes) because the shared volatility regime,
     not the shared bin, is the larger leak. No block spans midnight.
  3. TWO PURGED EXPOSURE SPLITS, because the obvious one is infeasible at the declared
     embargo. The exposure axis cannot be cut chronologically, so it is purged instead --
     but high-exposure windows are scattered through the tape rather than clustered, and
     embargoing every training window near one destroys the training set (measured at run
     time and recorded as `embargo_sweep`; at 30 windows nothing survives). Both variants
     are therefore built and reported:
       exposure_window  window-level tau split at a REDUCED embargo (EXPO_EMBARGO_WINDOWS,
                        default 2). Any embargo >= 1 removes the shared-bin overlap
                        entirely; 2 only partly breaks the shared volatility regime, and
                        that limitation is the reason the second variant exists.
       exposure_block   whole blocks assigned by median exposure, so the FULL embargo
                        applies and the purge matches the chronological split exactly.
                        The exposure contrast is weaker in exchange.
     If the two disagree, that disagreement is the finding, not a number to average.
  4. BOUNDARY AUDIT. `audit_split` re-derives, from the window indices themselves, that no
     train sample shares a bin with any test sample and that the minimum temporal gap is
     at least the embargo. It ASSERTS this rather than trusting the construction.

THE QUESTION THIS SCRIPT EXISTS TO ANSWER
-----------------------------------------
Previously, on the exposure axis, an oracle FITTED ON the exposure split scored 0.2866
while the same oracle TRANSFERRED FROM TRAIN scored 2.7877. A gap that large between
"achievable within the split" and "achievable from training data" is the signature of
DISTRIBUTION SHIFT rather than model failure -- but it was measured under the invalid
split, so it proved nothing either way. Here both oracles are recomputed under the purged
splits, AND the shift is measured directly (energy distance between train and test state
clouds, response clouds and exposure marginals), so the verdict rests on a measurement of
the shift and not on an inference from the gap. `diagnose_exposure_failure` returns the
verdict explicitly, with the numbers it rests on.

INDEPENDENT UNITS
-----------------
The PURGED BLOCK, never the window. Windows inside a block share a bin with their
neighbours and a volatility regime with the whole block; they are not independent
replicates. Every interval groups on the block id (see `metrics.py`).

Usage
    PYTHONPATH=src python experiments/finance_blocked.py --smoke
    PYTHONPATH=src python experiments/finance_blocked.py
"""
