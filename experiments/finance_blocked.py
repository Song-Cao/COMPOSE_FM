def main(smoke: bool = False, seed: int = 0, n_boot: int = 400,
         embargo: int = EMBARGO_WINDOWS,
         expo_embargo: int = EXPO_EMBARGO_WINDOWS) -> dict:
    t_start = time.time()
    print("loading windows", flush=True)
    W = load_windows()
    print("\nbuilding purged splits", flush=True)
    S = build_splits(W, embargo=embargo, expo_embargo=expo_embargo)
    splits, blocks = S["splits"], S["blocks"]

    steps = (40, 40, 20) if smoke else STEPS
    nb = 100 if smoke else n_boot

    out = dict(config=dict(smoke=bool(smoke), seed=int(seed), window=WINDOW,
                           d_state=D_STATE, k=K_CH, r=R_DEFAULT, hidden=HIDDEN, depth=DEPTH,
                           steps=list(steps), batch=BATCH, n_int_steps=N_INT_STEPS,
                           held_out_day=HELD_OUT_DAY, n_blocks_per_day=N_BLOCKS_PER_DAY,
                           embargo_windows=int(embargo),
                           exposure_embargo_windows=int(expo_embargo),
                           test_block_fraction=TEST_BLOCK_FRACTION,
                           tau_train_max=TAU_TRAIN_MAX, tau_test_min=TAU_TEST_MIN,
                           min_group=MIN_GROUP, n_tau_buckets=N_TAU_BUCKETS,
                           coupling=objective(seed).describe(),
                           n_pairs_representable=int(min(R_DEFAULT,
                                                         K_CH * (K_CH - 1) // 2)),
                           n_distinct_pairs=int(K_CH * (K_CH - 1) // 2),
                           rank_policy=("r is tunable capacity; the r >= k(k-1)/2 "
                                        "requirement is retracted. r=8 chosen because it "
                                        "measured best, and it happens to alias nothing "
                                        "at k=4."),
                           selection_metric=("distributional (normalised ED with its "
                                             "denominator) and CRPS; CFM loss is never "
                                             "used for model or coupling comparison"),
                           framing="observational order-flow conditioning, NOT causal "
                                   "intervention estimation",
                           state_names=dfin.IMPACT_STATE_NAMES,
                           run_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())),
               data=dict(files=list(W["files"]), n_windows=int(W["z0"].shape[0]),
                         n_blocks=int(np.unique(blocks).size)),
               splits={}, results={})

    # populations per split
    pops = {}
    for name, s in splits.items():
        out["splits"][name] = {k: v for k, v in s.items()
                               if k not in ("train", "test")}
        tr = make_populations(W, blocks, s["train"])
        te = make_populations(W, blocks, s["test"])
        if smoke:
            rng = np.random.default_rng(seed)
            # keep singletons: stage 1 raises without them
            so = [p for p in tr if p.order == 1]
            co = [p for p in tr if p.order >= 2]
            tr = ([so[i] for i in rng.permutation(len(so))[:20]]
                  + [co[i] for i in rng.permutation(len(co))[:20]])
            te = [te[i] for i in rng.permutation(len(te))[:12]]
        pops[name] = dict(train=tr, test=te)
        out["splits"][name].update(
            n_train_populations=len(tr), n_test_populations=len(te),
            n_train_singleton_populations=int(sum(p.order == 1 for p in tr)),
            n_test_blocks_with_populations=len({p.block for p in te}))
        print(f"  [{name:14s}] populations train {len(tr)} "
              f"({sum(p.order == 1 for p in tr)} singleton) / test {len(te)} "
              f"over {len({p.block for p in te})} blocks", flush=True)

    obj = objective(seed=seed)
    # ONE model, trained on the chronological training side, evaluated on all three
    # test sets. The exposure split has its own (purged, lower-exposure) training side,
    # so it gets its own model -- otherwise the "extrapolation" would be trained on the
    # very exposures it claims to extrapolate to.
    trained, fit_sets = {}, {}
    for arm in ("chronological", "exposure_window", "exposure_block"):
        print(f"\ntraining IHC-FM on the {arm} training side", flush=True)
        t0 = time.time()
        m = make_ihcfm(seed=seed)
        # `train_idx` and `val_idx` index the SAME population list, so the two sides must
        # be concatenated and indexed by offset. Passing range(len(test)) alongside a
        # train-only list -- as this originally did -- makes "validation" the first N
        # TRAINING populations, i.e. a training number recorded under a validation label.
        #
        # The validation side here is a held-out slice of the TRAINING blocks, never the
        # test split: monitoring on the test split would make every reported test number
        # selection-contaminated. Whole blocks are held out so the validation populations
        # share no block (hence no volatility regime and no bin) with what is trained on.
        tr_pops = pops[arm]["train"]
        # `fit_sets[arm]` is published so the scoring loop fits the BASELINES on exactly
        # what IHC-FM trained on. Without this the baselines get the validation blocks
        # too, i.e. strictly more data than the model they are paired against.

        tr_blocks = np.array(sorted({p.block for p in tr_pops}))
        rng_v = np.random.default_rng(seed + 31)
        n_val_blk = max(1, int(round(tr_blocks.size * 0.20)))
        val_blocks = set(rng_v.choice(tr_blocks, size=n_val_blk,
                                      replace=False).tolist())
        fit_pops = [p for p in tr_pops if p.block not in val_blocks]
        val_pops = [p for p in tr_pops if p.block in val_blocks]
        if not any(p.order == 1 for p in fit_pops) or not val_pops:
            # too small to carve a validation slice; train on everything and say so.
            # val_blocks must be cleared too, or the results json records a nonzero
            # held-out-block count under a validation label for a run that had none.
            fit_pops, val_pops, val_blocks = tr_pops, [], set()
        combined = fit_pops + val_pops
        fit_sets[arm] = fit_pops
        rep = train_hierarchical(m, combined, list(range(len(fit_pops))), objective=obj,
                                 val_idx=list(range(len(fit_pops), len(combined)))
                                 or None,
                                 steps=steps, batch=BATCH, lr=3e-3, seed=seed,
                                 verbose=False)
        out["results"].setdefault(arm, {})["validation"] = dict(
            n_fit_populations=len(fit_pops), n_val_populations=len(val_pops),
            n_val_blocks=len(val_blocks), carved=bool(val_pops),
            source=("held-out BLOCKS of the training side, never the test split"
                    if val_pops else
                    "NONE -- training side too small to carve a validation slice, so "
                    "the model trained on all of it and no validation was monitored"),
            note=("val_idx indexes the same concatenated population list as train_idx; "
                  "the two index ranges are disjoint by construction"))
        trained[arm] = m
        out["results"].setdefault(arm, {})["train_report"] = {
            s: {kk: vv for kk, vv in rep[s].items() if kk != "loss_history"}
            for s in ("stage1", "stage2", "stage3")}
        out["results"][arm]["skipped_nonfinite_total"] = int(rep["skipped_nonfinite_total"])
        out["results"][arm]["train_wall_clock_s"] = float(time.time() - t0)
        out["results"][arm]["n_parameters"] = int(sum(p.numel() for p in m.parameters()))
        print(f"  trained in {time.time()-t0:.0f}s "
              f"(skipped {rep['skipped_nonfinite_total']})", flush=True)

    # evaluate: chronological model on chronological + held-out day; exposure model on
    # the exposure split
    plan = [("chronological", "chronological"), ("held_out_day", "chronological"),
            ("exposure_window", "exposure_window"),
            ("exposure_block", "exposure_block")]
    for split_name, model_arm in plan:
        te = pops[split_name]["test"]
        # the model's ACTUAL fit set, so baselines and the denominator reference are
        # computed on identical data (see fit_sets above)
        tr = fit_sets.get(model_arm, pops[model_arm]["train"])
        if not te:
            out["results"].setdefault(split_name, {})["skipped"] = "no test populations"
            continue
        print(f"\nscoring [{split_name}] with the {model_arm}-trained model "
              f"({len(te)} populations)", flush=True)
        den_ref = float(np.median([
            M.energy_distance(p.pre, p.post, max_n=EVAL_MAX_N, seed=seed)
            for p in tr[:40]]))
        res = out["results"].setdefault(split_name, {})
        res["model_arm"] = model_arm
        res["train_denominator_reference"] = den_ref
        arms_rows = {}
        for arm_name, fn in (("ihcfm", ihcfm_predictor(trained[model_arm])),
                             ("perturbed_mean", None), ("no_change", None)):
            if arm_name == "perturbed_mean":
                bm = PerturbedMean(D_STATE, K_CH, seed=seed)
                bm.fit(tr, list(range(len(tr))))
                fn = lambda p, _m=bm: _m.predict(p.pre, p.P, p.tau)
            elif arm_name == "no_change":
                fn = lambda p: np.array(p.pre, copy=True)
            sc = score_split(te, fn, n_boot=nb, seed=seed, den_ref=den_ref)
            arms_rows[arm_name] = sc.pop("_rows")
            res.setdefault("arms", {})[arm_name] = sc
            s = sc["summary"]
            print(f"    {arm_name:15s} normED {s['ed_normalised']['point']:.4f} "
                  f"[{s['ed_normalised']['lo']:.4f}, {s['ed_normalised']['hi']:.4f}]  "
                  f"absED {s['ed_absolute']['point']:.4f}  "
                  f"denom {s['ed_denominator']['point']:.4f}  "
                  f"(n_blocks {s['ed_normalised']['n_groups']})", flush=True)
        # paired, on the same blocks, matched by population label
        res["paired"] = {}
        for a, b in (("ihcfm", "perturbed_mean"), ("ihcfm", "no_change")):
            ma = {r["condition"]: r for r in arms_rows[a]}
            mb = {r["condition"]: r for r in arms_rows[b]}
            common = sorted(set(ma) & set(mb))
            va = [ma[c]["ed_normalised"] for c in common]
            vb = [mb[c]["ed_normalised"] for c in common]
            g = [ma[c]["unit"] for c in common]
            ok = [i for i in range(len(va)) if np.isfinite(va[i]) and np.isfinite(vb[i])]
            if len(ok) >= 2:
                res["paired"][f"{a}_vs_{b}::ed_normalised"] = M.paired_group_difference(
                    [va[i] for i in ok], [vb[i] for i in ok], [g[i] for i in ok],
                    n_boot=nb, seed=seed, name_a=a, name_b=b)
                p = res["paired"][f"{a}_vs_{b}::ed_normalised"]
                print(f"    PAIRED {a} - {b}: {p['mean_diff']:+.4f} "
                      f"[{p['lo']:+.4f}, {p['hi']:+.4f}] sign p={p['sign_test_p']:.3g} "
                      f"over {p['n_units']} blocks", flush=True)
        # probabilistic scoring (finance-specific)
        res["probabilistic"] = probabilistic_scores(
            te, ihcfm_predictor(trained[model_arm]), seed=seed)
        if res["probabilistic"].get("summary"):
            ps = res["probabilistic"]["summary"]
            print(f"    CRPS {ps['crps']['point']:.5f} "
                  f"[{ps['crps']['lo']:.5f}, {ps['crps']['hi']:.5f}] vs no-change "
                  f"{ps['crps_no_change']['point']:.5f} | PIT central-90 "
                  f"{ps['pit_central_90']['point']:.3f} | KS "
                  f"{ps['pit_ks']['point']:.3f}", flush=True)
        # oracles + measured shift + verdict
        res["oracles"] = oracle_scores(tr, te, seed=seed)
        res["measured_shift"] = measure_shift(
            W, splits[model_arm]["train"], splits[split_name]["test"], seed=seed)
        res["diagnosis"] = diagnose_exposure_failure(
            res["oracles"], res["measured_shift"],
            res["arms"]["ihcfm"]["summary"], split_name=split_name)
        d = res["diagnosis"]
        print(f"    ORACLES transferred {d['oracle_transferred_normED']:.4f} vs "
              f"in-split {d['oracle_in_split_normED']:.4f} "
              f"(ratio {d['oracle_ratio']:.2f}) | measured shift ratio "
              f"{d['measured_shift_ratio']:.2f} | VERDICT {d['verdict']}", flush=True)

    out["wall_clock_total_s"] = float(time.time() - t_start)
    OUT.mkdir(exist_ok=True)
    tag = "_smoke" if smoke else ""
    jf = OUT / f"finance_blocked{tag}.json"
    json.dump(_jsonable(out), open(jf, "w"), indent=2)
    print(f"\nwrote {jf.relative_to(ROOT)} ({out['wall_clock_total_s']:.0f}s)", flush=True)
    return out


def _jsonable(o):
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, np.ndarray):
        return _jsonable(o.tolist())
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    return o


