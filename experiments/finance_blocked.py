def load_windows(cache: bool = True, verbose: bool = True) -> dict:
    """All windows from all days, with the CHRONOLOGICAL INDEX preserved per day.

    `w_index` is the within-day sample index, and it is what makes purging possible: it
    says which bins a sample touches (i and i+1), so overlap and temporal distance are
    computable rather than assumed. The previous version discarded it.
    """
    PROC.mkdir(parents=True, exist_ok=True)
    cf = PROC / f"finance_blocked_{WINDOW}.npz"
    if cache and cf.exists():
        z = np.load(cf, allow_pickle=True)
        if verbose:
            print(f"  loaded cache {cf.name}: {z['z0'].shape[0]} windows", flush=True)
        return {k: z[k] for k in ("z0r", "z1r", "tau", "day", "w_index", "z0", "z1")} | \
               dict(files=list(z["files"]), mu=z["mu"], sd=z["sd"])
    files = sorted(glob.glob(str(ROOT / "data/raw/finance/*.zip")))
    assert files, "no finance data found under data/raw/finance"
    Z0, Z1, TAU, DAY, WIX = [], [], [], [], []
    for i, f in enumerate(files):
        d = dfin.assign_channels(dfin.load_agg_trades(f))
        W = dfin.impact_state(d, window=WINDOW)
        n = W["z0"].shape[0]
        Z0.append(W["z0"]); Z1.append(W["z1"]); TAU.append(W["tau"])
        DAY.append(np.full(n, i, dtype=np.int64))
        WIX.append(np.arange(n, dtype=np.int64))
        if verbose:
            print(f"  {pathlib.Path(f).name}: {len(d)} trades -> {n} windows", flush=True)
    z0r = np.concatenate(Z0); z1r = np.concatenate(Z1)
    tau = np.concatenate(TAU); day = np.concatenate(DAY)
    w_index = np.concatenate(WIX)
    ok = (np.isfinite(z0r).all(1) & np.isfinite(z1r).all(1) & np.isfinite(tau).all(1))
    z0r, z1r, tau, day, w_index = (z0r[ok], z1r[ok], tau[ok], day[ok], w_index[ok])
    # Standardisation is fitted on the PRE-state of the TRAINING DAYS only. Fitting it on
    # all four days would let the held-out day's scale leak into the transform -- a small
    # leak, but this script exists to remove leaks.
    tr_days = day != HELD_OUT_DAY
    mu = z0r[tr_days].mean(0)
    sd = z0r[tr_days].std(0)
    bad = sd < 1e-8            # the pre-state return column is 0 by construction
    if bad.any():
        sd = sd.copy()
        sd[bad] = z1r[tr_days][:, bad].std(0)
    sd = sd + 1e-9
    out = dict(z0r=z0r, z1r=z1r, tau=tau, day=day, w_index=w_index,
               z0=(z0r - mu) / sd, z1=(z1r - mu) / sd,
               files=[pathlib.Path(f).name for f in files], mu=mu, sd=sd)
    if cache:
        np.savez_compressed(cf, **{k: np.asarray(v) for k, v in out.items()})
    if verbose:
        print(f"  {z0r.shape[0]} windows total | standardisation fitted on "
              f"{int(tr_days.sum())} training-day windows", flush=True)
    return out


# ==================================================================================
# blocks and purged splits
# ==================================================================================
def assign_blocks(day: np.ndarray, w_index: np.ndarray,
                  n_per_day: int = N_BLOCKS_PER_DAY) -> np.ndarray:
    """Contiguous within-day blocks -- the INDEPENDENT UNIT. No block spans midnight.

    Blocks are cut on the chronological index, so each is a contiguous stretch of tape
    (2 h at the default). Windows within a block share a volatility regime; windows in
    different blocks of the same day still share the day, which is why the fully held-out
    day exists as a separate, stricter test.
    """
    blocks = np.empty(day.shape[0], dtype=np.int64)
    for d in np.unique(day):
        m = day == d
        wi = w_index[m]
        edges = np.linspace(wi.min(), wi.max() + 1, int(n_per_day) + 1)
        b = np.clip(np.searchsorted(edges, wi, side="right") - 1, 0, int(n_per_day) - 1)
        blocks[m] = d * 1000 + b
    return blocks


def purge_against(day: np.ndarray, w_index: np.ndarray, cand: np.ndarray,
                  test: np.ndarray, embargo: int = EMBARGO_WINDOWS) -> np.ndarray:
    """Drop candidate samples within `embargo` windows of ANY test sample on the same day.

    This is the operation that makes the split valid. A gap of 1 already removes the
    SHARED-BIN overlap (sample i and i+1 both use bin i+1); the wider embargo additionally
    breaks the shared short-horizon volatility regime, which is the larger leak at a 10 s
    sampling scale. Purging is applied to the TRAINING side, so the test set is never
    modified to flatter a model.
    """
    keep = np.ones(cand.shape[0], dtype=bool)
    for d in np.unique(day[test]):
        t_wi = np.sort(w_index[test][day[test] == d])
        c_local = np.nonzero(day[cand] == d)[0]
        if c_local.size == 0 or t_wi.size == 0:
            continue
        c_wi = w_index[cand][c_local]
        pos = np.searchsorted(t_wi, c_wi)
        lo = np.clip(pos - 1, 0, t_wi.size - 1)
        hi = np.clip(pos, 0, t_wi.size - 1)
        dist = np.minimum(np.abs(c_wi - t_wi[lo]), np.abs(c_wi - t_wi[hi]))
        keep[c_local[dist <= int(embargo)]] = False
    return cand[keep]


def audit_split(day: np.ndarray, w_index: np.ndarray, train: np.ndarray,
                test: np.ndarray, embargo: int = EMBARGO_WINDOWS) -> dict:
    """RE-DERIVE, from the indices, that the split leaks nothing. Asserts, does not trust.

    Checks
    ------
    disjoint            train and test index sets do not intersect
    no_shared_bin       no train sample shares EITHER of its two bins (i, i+1) with any
                        test sample on the same day. This is the concrete overlap the
                        previous split permitted.
    min_gap             the smallest same-day |w_index| distance between a train and a
                        test sample, which must be > embargo
    """
    inter = np.intersect1d(train, test)
    min_gap, shared = np.inf, 0
    for d in np.unique(day):
        tr = np.sort(w_index[train][day[train] == d])
        te = np.sort(w_index[test][day[test] == d])
        if tr.size == 0 or te.size == 0:
            continue
        pos = np.searchsorted(te, tr)
        lo = np.clip(pos - 1, 0, te.size - 1)
        hi = np.clip(pos, 0, te.size - 1)
        g = np.minimum(np.abs(tr - te[lo]), np.abs(tr - te[hi]))
        min_gap = min(min_gap, float(g.min()))
        # bins touched: sample i occupies {i, i+1}
        tr_bins = np.union1d(tr, tr + 1)
        te_bins = np.union1d(te, te + 1)
        shared += int(np.intersect1d(tr_bins, te_bins).size)
    return dict(n_train=int(train.size), n_test=int(test.size),
                disjoint=bool(inter.size == 0), n_overlapping_indices=int(inter.size),
                n_shared_bins=int(shared), no_shared_bin=bool(shared == 0),
                min_same_day_gap_windows=(None if not np.isfinite(min_gap)
                                          else float(min_gap)),
                embargo_windows=int(embargo),
                gap_respects_embargo=bool(not np.isfinite(min_gap)
                                          or min_gap > embargo),
                days_train=[int(x) for x in np.unique(day[train])],
                days_test=[int(x) for x in np.unique(day[test])])


def _sweep_at(sweep: list[dict], embargo: int):
    """Retention measured at `embargo` in THIS run's sweep, or None if not swept."""
    for row in sweep:
        if int(row["embargo"]) == int(embargo):
            return int(row["n_train_kept"])
    return None


def build_splits(W: dict, embargo: int = EMBARGO_WINDOWS,
                 expo_embargo: int = EXPO_EMBARGO_WINDOWS,
                 verbose: bool = True) -> dict:
    """The three purged splits plus the fully held-out day, each with its audit."""
    day, wi, tau = W["day"], W["w_index"], W["tau"]
    blocks = assign_blocks(day, wi)
    tau_max = tau.max(1)
    k_act = (tau > 0).sum(1)
    all_idx = np.arange(day.shape[0])

    # --- fully held-out day ---------------------------------------------------------
    day_test = all_idx[day == HELD_OUT_DAY]
    pool = all_idx[day != HELD_OUT_DAY]          # everything the model may ever see

    # --- purged chronological split WITHIN the training days ------------------------
    ub = np.array(sorted(np.unique(blocks[pool])))
    n_test_blocks = max(1, int(round(len(ub) * TEST_BLOCK_FRACTION)))
    # chronological: block ids are day*1000 + b, so sorting is chronological order
    test_blocks = ub[-n_test_blocks:]
    chrono_test = pool[np.isin(blocks[pool], test_blocks)]
    chrono_train_raw = pool[~np.isin(blocks[pool], test_blocks)]
    chrono_train = purge_against(day, wi, chrono_train_raw, chrono_test, embargo)

    # --- EXPOSURE splits: two variants, because the obvious one is INFEASIBLE ---------
    # A window-level exposure split cannot carry a wide embargo. High-exposure windows are
    # scattered through the tape rather than clustered, so embargoing every low-exposure
    # window near a high-exposure one destroys the training set. The sweep below is
    # computed AT RUN TIME on the candidate pool this function actually uses
    # (`chrono_train_raw`) and is recorded in the result as `embargo_sweep`; the reported
    # numbers therefore always describe the split that was built. A reference measurement
    # over all non-held-out-day windows -- a LARGER pool than the one used here, so its
    # counts differ -- showed the same qualitative picture: 100% retained at embargo 0,
    # 43.9% at 2, 3.6% at 10 and 0% at 30. Rather than silently shrink the embargo (which
    # would hide a real limitation), both variants are built and reported:
    #
    #   exposure_window  window-level tau split at the LARGEST embargo that still retains
    #                    a usable training set (`expo_embargo`, default 2). This removes
    #                    the shared-bin overlap completely (any embargo >= 1 does) but
    #                    only partly breaks the shared volatility regime. Its own sweep is
    #                    recorded in the result so the reader sees the trade.
    #   exposure_block   whole BLOCKS assigned by their median exposure -- low-exposure
    #                    blocks train, high-exposure blocks test. Contiguous by
    #                    construction, so the full embargo applies and the split is purged
    #                    exactly like the chronological one. The exposure CONTRAST is
    #                    weaker (block medians span 1.21 to 7.44 rather than window-level
    #                    <=3 vs >=6), which is the price of a clean purge.
    # Reporting both is the point: they bracket the answer, and if they disagree that
    # disagreement is itself the finding.
    sweep = []
    for e in (0, 1, 2, 5, 10, 30, 60):
        cand = chrono_train_raw[tau_max[chrono_train_raw] <= TAU_TRAIN_MAX]
        te = chrono_train_raw[tau_max[chrono_train_raw] >= TAU_TEST_MIN]
        kept = purge_against(day, wi, cand, te, e)
        sweep.append(dict(embargo=int(e), n_train_kept=int(kept.size),
                          fraction_kept=float(kept.size / max(cand.size, 1))))
    expo_test = chrono_train_raw[tau_max[chrono_train_raw] >= TAU_TEST_MIN]
    expo_cand = chrono_train_raw[tau_max[chrono_train_raw] <= TAU_TRAIN_MAX]
    expo_train = purge_against(day, wi, expo_cand, expo_test, expo_embargo)

    # block-level exposure split
    blk_ids = np.array(sorted(np.unique(blocks[pool])))
    blk_tau = np.array([float(np.median(tau_max[pool][blocks[pool] == b]))
                        for b in blk_ids])
    o = np.argsort(blk_tau)
    n_hi = max(1, int(round(blk_ids.size * 0.30)))
    hi_blocks, lo_blocks = blk_ids[o][-n_hi:], blk_ids[o][:blk_ids.size - n_hi]
    eb_test = pool[np.isin(blocks[pool], hi_blocks)]
    eb_train = purge_against(day, wi, pool[np.isin(blocks[pool], lo_blocks)],
                             eb_test, embargo)

    sp = dict(
        chronological=dict(name="chronological", train=chrono_train, test=chrono_test,
                           note=("last %.0f%% of blocks held out; embargo applied to the "
                                 "TRAINING side only, test left intact"
                                 % (100 * TEST_BLOCK_FRACTION))),
        held_out_day=dict(name="held_out_day", train=chrono_train, test=day_test,
                          note=f"day index {HELD_OUT_DAY} removed before any fitting"),
        exposure_window=dict(
            name="exposure_window", train=expo_train, test=expo_test,
            embargo_used=int(expo_embargo), embargo_sweep=sweep,
            note=(f"window-level: train tau_max<={TAU_TRAIN_MAX}, test tau_max>="
                  f"{TAU_TEST_MIN}, embargo {expo_embargo} reduced from {embargo}; "
                  f"retention at the full {embargo}-window embargo was "
                  f"{_sweep_at(sweep, embargo)} training windows (from this run's own "
                  "embargo_sweep, not a stored constant)")),
        exposure_block=dict(
            name="exposure_block", train=eb_train, test=eb_test,
            note=(f"block-level: {n_hi} highest-median-exposure blocks test, rest train, "
                  f"full {embargo}-window embargo; block median tau_max "
                  f"{blk_tau.min():.2f}..{blk_tau.max():.2f}"),
            block_median_tau_range=[float(blk_tau.min()), float(blk_tau.max())],
            test_block_median_tau=float(np.median(blk_tau[o][-n_hi:])),
            train_block_median_tau=float(np.median(blk_tau[o][:blk_ids.size - n_hi]))),
    )
    for s in sp.values():
        # Each split is audited against ITS OWN embargo. exposure_window deliberately
        # runs a smaller one (the full embargo retains zero training windows -- see
        # embargo_sweep), so auditing it against the global value would fail on a
        # documented, reported trade-off rather than on a leak. The shared-bin check is
        # embargo-independent and still applies at full strength to every split.
        s_emb = int(s.get("embargo_used", embargo))
        s["audit"] = audit_split(day, wi, s["train"], s["test"], s_emb)
        s["n_train_blocks"] = int(np.unique(blocks[s["train"]]).size)
        s["n_test_blocks"] = int(np.unique(blocks[s["test"]]).size)
        s["train_tau_max_median"] = float(np.median(tau_max[s["train"]]))
        s["test_tau_max_median"] = float(np.median(tau_max[s["test"]]))
        s["train_k_active_mean"] = float(np.mean(k_act[s["train"]]))
        s["test_k_active_mean"] = float(np.mean(k_act[s["test"]]))
        if verbose:
            a = s["audit"]
            print(f"  [{s['name']:14s}] train {a['n_train']:6d} / test {a['n_test']:6d}"
                  f" | blocks {s['n_train_blocks']}/{s['n_test_blocks']}"
                  f" | shared bins {a['n_shared_bins']}"
                  f" | min gap {a['min_same_day_gap_windows']}"
                  f" | tau_max med {s['train_tau_max_median']:.2f} ->"
                  f" {s['test_tau_max_median']:.2f}", flush=True)
        # Hard assertions: a leaking split must stop the run, not annotate it.
        assert a["disjoint"], f"{s['name']}: train/test intersect"
        assert a["no_shared_bin"], (f"{s['name']}: {a['n_shared_bins']} shared bins -- "
                                    "the exact leak this script exists to remove")
        assert a["gap_respects_embargo"], (
            f"{s['name']}: min gap {a['min_same_day_gap_windows']} <= its embargo {s_emb}")
    return dict(splits=sp, blocks=blocks)


# ==================================================================================
# populations: (block, active-channel set, exposure bucket)
# ==================================================================================
def make_populations(W: dict, blocks: np.ndarray, idx: np.ndarray,
                     min_group: int = MIN_GROUP, n_buckets: int = N_TAU_BUCKETS) -> list:
    """Group windows into populations the hierarchy can consume.

    The hierarchy's contract is one intervention SET and one scalar exposure per
    population (`.P`, `.tau`, `.pre`, `.post`). Finance gives a per-window exposure
    VECTOR, so windows are grouped by (block, active-channel set, exposure bucket) and the
    bucket's MEDIAN tau over its active channels is used as the population exposure. Two
    honest consequences, stated because they weaken what the exposure axis can show:
      * bucketing discards within-bucket exposure variation, so the fitted dose response
        is resolved at bucket granularity, not per window;
      * `block` is carried on every population and IS the bootstrap unit, so grouping does
        not manufacture independent replicates -- populations from one block stay one unit.
    """
    z0, z1, tau = W["z0"], W["z1"], W["tau"]
    from collections import defaultdict
    groups = defaultdict(list)
    for i in idx:
        # activity floor, not "any trade" -- see CHANNEL_ACTIVITY_FLOOR: with a floor of 0
        # there are no singleton windows anywhere in the data and the hierarchy's stage 1
        # is unidentifiable.
        act = tuple(np.nonzero(tau[i] > CHANNEL_ACTIVITY_FLOOR)[0].tolist())
        if not act:
            continue
        groups[(int(blocks[i]), act)].append(int(i))
    pops = []
    for (blk, act), members in groups.items():
        members = np.array(members)
        tm = np.array([float(np.median(tau[i, list(act)])) for i in members])
        if members.size < min_group:
            continue
        # quantile buckets on the group's own exposure, so buckets are populated
        qs = np.quantile(tm, np.linspace(0, 1, int(n_buckets) + 1))
        qs[0] -= 1e-12
        bkt = np.clip(np.searchsorted(qs, tm, side="right") - 1, 0, int(n_buckets) - 1)
        for b in range(int(n_buckets)):
            sel = members[bkt == b]
            if sel.size < max(8, min_group // n_buckets):
                continue
            pops.append(FinPop(
                label=f"b{blk}_c{''.join(map(str, act))}_t{b}",
                P=tuple(int(c) for c in act),
                tau=float(np.median(tm[bkt == b])),
                pre=np.asarray(z0[sel], dtype=np.float64),
                post=np.asarray(z1[sel], dtype=np.float64),
                block=int(blk), window_indices=W["w_index"][sel],
                day=int(W["day"][sel][0]), n_windows=int(sel.size)))
    return pops


class FinPop:
    """Duck-typed for the hierarchy (.P, .tau, .pre, .post) plus its provenance.

    `block` is the independent unit; `window_indices` is retained so the purge audit can
    be re-derived from the populations themselves rather than from the index arrays.
    """

    def __init__(self, label, P, tau, pre, post, block, window_indices, day, n_windows):
        self.label, self.P, self.tau = label, P, float(tau)
        self.pre, self.post = pre, post
        self.block, self.window_indices = int(block), window_indices
        self.day, self.n_windows = int(day), int(n_windows)

    @property
    def order(self) -> int:
        return len(self.P)


