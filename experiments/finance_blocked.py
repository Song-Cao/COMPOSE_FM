def probabilistic_scores(pops: list, predict_fn, coord: int = 0,
                         quantiles=(0.1, 0.25, 0.5, 0.75, 0.9), seed: int = 0) -> dict:
    """CRPS, PIT calibration and quantile loss on the RETURN coordinate.

    The model transports a CLOUD of windows, so the predicted cloud for one population is
    a genuine predictive ensemble for that population's response distribution. Coordinate
    `coord` is 0 = the realised log return (see `data_finance.IMPACT_STATE_NAMES`), which
    is the quantity a risk application cares about; the observations scored against it are
    the individual observed post-state returns in that population.

    ONE ENSEMBLE PER POPULATION, not per window. The transport is not paired -- window j's
    predicted point is not a forecast of window j's realised return -- so pairing them
    would score an alignment the model never claimed. Every observation in a population is
    scored against the population's whole predicted ensemble, which is the distributional
    claim the model actually makes. CRPS is then averaged within a population before the
    block-level bootstrap, so a large population does not dominate its block.
    """
    rows = []
    for p in pops:
        pred = np.asarray(predict_fn(p), dtype=np.float64)
        ens = pred[:, coord]
        obs = np.asarray(p.post, dtype=np.float64)[:, coord]
        ctrl = np.asarray(p.pre, dtype=np.float64)[:, coord]
        if ens.size < 4 or obs.size < 2:
            continue
        S = np.tile(ens[None, :], (obs.size, 1))
        S_ctrl = np.tile(ctrl[None, :], (obs.size, 1))
        cov = M.pit_coverage(S, obs)
        ql = M.quantile_loss(S, obs, quantiles=quantiles)
        rows.append(dict(unit=f"blk{p.block}", condition=p.label, block=int(p.block),
                         day=int(p.day), n_obs=int(obs.size), n_ensemble=int(ens.size),
                         crps=float(np.mean([M.crps_ensemble(ens, y) for y in obs])),
                         crps_no_change=float(np.mean(
                             [M.crps_ensemble(ctrl, y) for y in obs])),
                         quantile_loss=float(ql["mean_loss"]),
                         quantile_loss_no_change=float(
                             M.quantile_loss(S_ctrl, obs, quantiles=quantiles)["mean_loss"]),
                         pit_ks=float(cov["ks_uniform"]),
                         pit_central_50=float(cov["central_0.5"]),
                         pit_central_90=float(cov["central_0.9"]),
                         pit_mean=float(cov["mean_pit"])))
    if not rows:
        return dict(n_populations=0)
    out = dict(per_population=rows,
               summary=M.summarise_per_unit(
                   rows, metrics=["crps", "crps_no_change", "quantile_loss",
                                  "quantile_loss_no_change", "pit_ks", "pit_central_50",
                                  "pit_central_90", "pit_mean"],
                   n_boot=400, seed=seed))
    out["paired_crps_vs_no_change"] = M.paired_group_difference(
        [r["crps"] for r in rows], [r["crps_no_change"] for r in rows],
        [r["unit"] for r in rows], n_boot=400, seed=seed,
        name_a="model", name_b="no_change")
    out["calibration_note"] = (
        "PIT central-50 / central-90 far below 0.5 / 0.9 means the predicted ensemble is "
        "too NARROW (over-confident); far above means too wide. ks_uniform is the single "
        "scalar summary of miscalibration.")
    return out


