# oracles -- the distribution-shift diagnosis
# ==================================================================================
def oracle_scores(pops_train: list, pops_test: list, seed: int = 0) -> dict:
    """Two mean-shift oracles, which together separate SHIFT from MODEL FAILURE.

    transferred  one mean shift per (channel-set, exposure bucket) FITTED ON TRAIN and
                 applied to test. This is the best any shift-based method could do using
                 only training data, so it is an upper bound on what a fitted model can
                 be expected to achieve on the test split.
    in_split     the same construction FITTED ON THE TEST SPLIT ITSELF. Not achievable in
                 practice -- it peeks -- but it measures how much signal the test split
                 CONTAINS. It is the ceiling.

    Reading the pair:
      in_split good AND transferred bad  -> the split contains predictable structure that
          training data does not carry: DISTRIBUTION SHIFT.
      both bad -> the split is intrinsically unpredictable at this granularity; no model
          failure to diagnose either.
      transferred ~ in_split -> no shift; a model scoring worse than transferred is a
          genuine MODEL failure.
    The verdict is not read off this pair alone -- `diagnose_exposure_failure` also
    measures the shift directly -- but this is the comparison the previous study made, so
    it is recomputed here on a valid split.
    """
    def _key(p):
        return (tuple(sorted(p.P)), round(float(p.tau), 1))

    def _fit(pops):
        from collections import defaultdict
        acc = defaultdict(list)
        for p in pops:
            acc[_key(p)].append(p.post.mean(0) - p.pre.mean(0))
        return {k: np.mean(np.stack(v, 0), 0) for k, v in acc.items()}

    def _score(table, pops, fallback):
        rows = []
        for p in pops:
            s = table.get(_key(p), fallback)
            rows.append(dict(unit=f"blk{p.block}", condition=p.label,
                             pred=p.pre + s[None, :], true=p.post, ctrl=p.pre,
                             block=int(p.block), day=int(p.day),
                             order=int(p.order)))
        return M.score_records(rows, seed=seed, max_n=EVAL_MAX_N, n_slices=64)

    t_tr = _fit(pops_train)
    t_te = _fit(pops_test)
    fb_tr = (np.mean(np.stack(list(t_tr.values()), 0), 0) if t_tr
             else np.zeros(D_STATE))
    fb_te = (np.mean(np.stack(list(t_te.values()), 0), 0) if t_te
             else np.zeros(D_STATE))
    r_tr = _score(t_tr, pops_test, fb_tr)
    r_te = _score(t_te, pops_test, fb_te)
    n_missing = sum(1 for p in pops_test if _key(p) not in t_tr)
    return dict(
        transferred=M.summarise_per_unit(r_tr, n_boot=400, seed=seed),
        in_split=M.summarise_per_unit(r_te, n_boot=400, seed=seed),
        n_test_conditions=len(pops_test),
        n_test_conditions_absent_from_train=int(n_missing),
        fraction_test_conditions_unseen=float(n_missing / max(len(pops_test), 1)),
        paired_transferred_vs_in_split=M.paired_group_difference(
            [r["ed_normalised"] for r in r_tr], [r["ed_normalised"] for r in r_te],
            [r["unit"] for r in r_tr], n_boot=400, seed=seed,
            name_a="transferred", name_b="in_split"))


def measure_shift(W: dict, train: np.ndarray, test: np.ndarray, seed: int = 0) -> dict:
    """Measure the train->test distribution shift DIRECTLY, not by inference from a gap.

    Three separate clouds are compared, because they answer different questions:
      pre_state   ED(train z0, test z0)  -- are the conditioning states different?
      response    ED(train dz, test dz)  -- are the responses different?
      exposure    per-channel tau marginals (1-d sliced W2 and the median ratio)
    Each energy distance is reported next to a WITHIN-TRAIN baseline: two disjoint halves
    of the training set scored the same way. That baseline is the crucial control -- an
    energy distance means nothing without knowing what the same statistic reads on two
    samples that are NOT shifted.
    """
    rng = np.random.default_rng(seed)

    def _sub(ix, n=1500):
        return ix if ix.size <= n else rng.choice(ix, n, replace=False)

    a, b = _sub(train), _sub(test)
    h = rng.permutation(train)
    h1, h2 = _sub(h[: h.size // 2]), _sub(h[h.size // 2:])
    dz_tr = W["z1"][a] - W["z0"][a]
    dz_te = W["z1"][b] - W["z0"][b]
    dz_h1 = W["z1"][h1] - W["z0"][h1]
    dz_h2 = W["z1"][h2] - W["z0"][h2]
    out = dict(
        pre_state_ed=M.energy_distance(W["z0"][a], W["z0"][b], seed=seed),
        pre_state_ed_within_train=M.energy_distance(W["z0"][h1], W["z0"][h2], seed=seed),
        response_ed=M.energy_distance(dz_tr, dz_te, seed=seed),
        response_ed_within_train=M.energy_distance(dz_h1, dz_h2, seed=seed),
        pre_state_mmd=M.mmd_rbf(W["z0"][a], W["z0"][b], seed=seed)["mmd2"],
        pre_state_mmd_within_train=M.mmd_rbf(W["z0"][h1], W["z0"][h2],
                                             seed=seed)["mmd2"],
        n_train_sampled=int(a.size), n_test_sampled=int(b.size))
    tau = W["tau"]
    out["exposure_per_channel"] = [
        dict(channel=int(c), name=dfin.CHANNEL_NAMES[c],
             train_median=float(np.median(tau[train, c])),
             test_median=float(np.median(tau[test, c])),
             median_ratio=float(np.median(tau[test, c])
                                / max(np.median(tau[train, c]), 1e-12)),
             sliced_w2=M.sliced_wasserstein(tau[a, c][:, None], tau[b, c][:, None],
                                            n_slices=1, seed=seed))
        for c in range(K_CH)]
    for key in ("pre_state", "response"):
        base = max(out[f"{key}_ed_within_train"], 1e-12)
        out[f"{key}_shift_ratio"] = float(out[f"{key}_ed"] / base)
    return out


def diagnose_exposure_failure(oracle: dict, shift: dict, model_summary: dict,
                              split_name: str = "") -> dict:
    """State the VERDICT on the exposure axis, with the numbers it rests on.

    Decision rule, fixed before the numbers were seen:
      * SHIFT if the transferred oracle is materially worse than the in-split oracle
        (paired interval excludes zero AND the ratio exceeds 1.5x) AND the measured
        pre-state or response shift ratio exceeds 3x its within-train baseline.
      * MODEL FAILURE if the two oracles agree (paired interval contains zero) and the
        fitted model is nonetheless worse than the transferred oracle.
      * UNINFORMATIVE SPLIT if both oracles are poor (in-split normED >= 1), i.e. the
        split contains little predictable structure for ANY shift-based predictor.
    Anything else is reported as MIXED with the components, rather than forced into a box.
    """
    tr = oracle["transferred"]["ed_normalised"]["point"]
    ins = oracle["in_split"]["ed_normalised"]["point"]
    pr = oracle["paired_transferred_vs_in_split"]
    ratio = float(tr / max(ins, 1e-12))
    shift_ratio = max(shift["pre_state_shift_ratio"], shift["response_shift_ratio"])
    mdl = (model_summary or {}).get("ed_normalised", {}).get("point", float("nan"))
    oracles_differ = bool(pr["excludes_zero"] and ratio > 1.5)
    big_shift = bool(shift_ratio > 3.0)
    if ins >= 1.0:
        verdict = "uninformative_split"
    elif oracles_differ and big_shift:
        verdict = "distribution_shift"
    elif not pr["excludes_zero"] and np.isfinite(mdl) and mdl > tr:
        verdict = "model_failure"
    else:
        verdict = "mixed"
    # The prior 0.2866 / 2.7877 pair was measured on the EXPOSURE axis specifically, so it
    # is attached only to exposure splits. Emitting it under `chronological` or
    # `held_out_day` would invite a comparison against numbers from a different axis.
    prev = None
    if split_name.startswith("exposure"):
        prev = dict(oracle_in_split=0.2866, oracle_transferred=2.7877,
                    axis="exposure",
                    note=("measured on the exposure axis under a split that allowed "
                          "window overlap; recomputed here under the purged split. Not "
                          "comparable to the chronological or held-out-day splits, which "
                          "have no corresponding prior number."))
    return dict(verdict=verdict, split=str(split_name),
                previous_invalid_split=prev,
                oracle_transferred_normED=float(tr), oracle_in_split_normED=float(ins),
                oracle_ratio=ratio,
                oracle_paired_excludes_zero=bool(pr["excludes_zero"]),
                oracle_paired_diff=float(pr["mean_diff"]),
                oracle_paired_ci=[float(pr["lo"]), float(pr["hi"])],
                measured_shift_ratio=float(shift_ratio),
                pre_state_shift_ratio=float(shift["pre_state_shift_ratio"]),
                response_shift_ratio=float(shift["response_shift_ratio"]),
                fitted_model_normED=float(mdl),
                fraction_test_conditions_unseen=float(
                    oracle["fraction_test_conditions_unseen"]),
                rule=("SHIFT: oracles differ (paired CI excludes 0 and ratio>1.5) AND "
                      "measured shift ratio>3x within-train baseline. FAILURE: oracles "
                      "agree but the fitted model is worse than transferred. "
                      "UNINFORMATIVE: in-split oracle normED>=1."))


