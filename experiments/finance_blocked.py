def score_split(pops_test: list, predict_fn, n_boot: int, seed: int = 0,
                den_ref: float | None = None) -> dict:
    recs = [dict(unit=f"blk{p.block}", condition=p.label, block=int(p.block),
                 day=int(p.day), order=int(p.order),
                 pred=np.asarray(predict_fn(p), dtype=np.float64),
                 true=p.post, ctrl=p.pre) for p in pops_test]
    rows = M.score_records(recs, seed=seed, max_n=EVAL_MAX_N, n_slices=64)
    return dict(per_population=rows,
                summary=M.summarise_per_unit(rows, n_boot=n_boot, seed=seed),
                denominator_check=M.flag_denominator_collapse(rows, reference=den_ref),
                residualised=(M.residualised_report(recs, max_n=EVAL_MAX_N, seed=seed)
                              if len(recs) >= 2 else None),
                _rows=rows)


