class PullbackAdapter(torch.nn.Module):
    """`PullbackField(t, z, one_form=...)` -> the `pullback(t, z, b)` contract, as a MODULE.

    A closure would be invisible to `nn.Module` registration, so `to_inference_dtype()`
    would cast the velocity net to float64 while leaving the decoder inside the pullback in
    float32 (project fact D requires the float64 path). Registering it casts the whole
    composed field together.
    """

    def __init__(self, field: PullbackField):
        super().__init__()
        self.field = field

    def forward(self, t, z, b):
        return self.field(t, z, one_form=lambda tt, xx, cc: b)


def make_ihcfm(d: int = D_STATE, k: int = K_CH, r: int = R_DEFAULT, code_dim: int = 0,
               hidden: int = HIDDEN, depth: int = DEPTH, seed: int = 0,
               interaction_enabled: bool = True) -> ConditionalVelocity:
    """The FULL model. `interaction_enabled` / `code_dim` are ablation flags, full by default."""
    torch.manual_seed(int(seed))
    dec = Decoder(int(d), int(d), hidden=32, s=0.5, seed=int(seed))
    met = AmbientMetric(int(d), hidden=48, w_min=0.25, l_cap=1.5)
    sat = MetricRadialSat(x_dim=int(d), latent_dim=int(d), hidden=32,
                          mode="metric_radial", kappa_init=2.0)
    pbf = PullbackField(dec, met, saturator=sat)
    dose = HillDose(int(k), amp_init=1.0, ec50_init=1.0, hill_init=1.0)
    return ConditionalVelocity(int(d), int(k), r=int(r), code_dim=int(code_dim),
                               hidden=int(hidden), depth=int(depth), dose=dose,
                               pullback=PullbackAdapter(pbf), decoder=dec,
                               interaction_enabled=bool(interaction_enabled))


def objective(seed: int = 0) -> CFMObjective:
    """I-CFM with unbalanced-Sinkhorn coupling ("sinkhorn_uot" = this exact kwarg set).

    CFM LOSS IS NOT USED TO SELECT OR COMPARE COUPLINGS ANYWHERE IN THIS SCRIPT. CFM loss
    tracks the fraction of trivially identical source/target pairs a coupling produces
    (identity-pair fraction: paired 1.0, ot 0.795, sinkhorn 0.229, independent 0.0039), so
    a coupling can win it by making the regression target trivial. On the distributional
    metric the ranking inverts: normalised ED independent 0.8094, sinkhorn_uot 0.8387,
    ot 1.1188 -- `ot` is worse than predicting no change. This coupling was re-selected on
    ground-truth interaction recovery, where sinkhorn_uot wins at every rank.

    There is no coupling="sinkhorn_uot" string; the label means the kwargs below.
    """
    return CFMObjective(sigma=0.0, coupling="sinkhorn", sinkhorn_eps=0.05,
                        sinkhorn_iters=25, unbalanced_tau=1.0, seed=int(seed),
                        max_coupling_n=128)


